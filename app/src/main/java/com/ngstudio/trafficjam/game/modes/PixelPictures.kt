    /**
     * How demanding a picture is: every extra color means more kinds of bus (or truck) to
     * juggle, and more cells mean more riders (or sand) to clear.
     */
    private fun complexity(p: PixelPicture) = p.colors(false).size * 12f + p.cells.count { it >= 0 } / 10f

    /** A picture never comes back within this many levels. */
    private const val RECENT = 20

    /** Picture indexes from simplest to most complex. */
    private val ranked: List<Int> = all.indices.sortedBy { complexity(all[it]) }

    /**
     * Which picture each level shows, and how many times that picture was shown before.
     *
     * Levels 1..[all].size show every picture once, simplest first, so each early level brings
     * a new picture and the pictures get busier as the player learns. After that the pictures
     * are dealt in shuffled decks: a picture never comes back until the whole deck has been
     * played, and the simplest ones slowly drop out of the late-game decks. Breather levels
     * draw from the simpler half and Super Hard levels from the busier half of each deck.
     */
    private val schedule: Pair<IntArray, IntArray> by lazy {
        val total = 5000
        val picOf = IntArray(total + 1)
        val seenBefore = IntArray(total + 1)
        val count = IntArray(all.size)
        var n = 1
        for (p in ranked) {
            if (n > total) break
            picOf[n] = p; seenBefore[n] = count[p]++; n++
        }
        var deck = 0
        val recent = ArrayDeque<Int>()
        for (k in maxOf(1, n - RECENT) until n) recent.addLast(picOf[k])
        while (n <= total) {
            // Late decks leave out the very simplest pictures (up to a quarter of them).
            val skip = (all.size * 0.25f * ((n - 300).coerceIn(0, 1200) / 1200f)).toInt()
            val cards = ranked.drop(skip).shuffled(kotlin.random.Random(deck * 7_919L + 17)).toMutableList()
            while (cards.isNotEmpty() && n <= total) {
                val easy = n % 10 == 1 || n % 10 == 6
                val superHard = n % 10 == 0
                // Nothing shown in the last RECENT levels, even across decks (decks are bigger
                // than twice that, so there is always a fresh card).
                val options = cards.filter { it !in recent }.ifEmpty { cards }
                // Peaks and breathers pick from the matching end of what is left in the deck.
                val pick = when {
                    superHard -> options.maxBy { complexity(all[it]) }
                    easy -> options.minBy { complexity(all[it]) }
                    else -> options.first()
                }
                cards.remove(pick)
                picOf[n] = pick; seenBefore[n] = count[pick]++; n++
                recent.addLast(pick)
                if (recent.size > RECENT) recent.removeFirst()
            }
            deck++
        }
        picOf to seenBefore
    }

    /**
     * The picture for level [n]. A picture's second showing is mirrored, and every showing after
     * that also swaps its colors around, so a returning picture looks new.
     */
    fun forLevel(n: Int): PixelPicture {
        val (picOf, seenBefore) = schedule
        val level = n.coerceIn(1, picOf.size - 1)
        var p = all[picOf[level]]
        val seen = seenBefore[level]
        if (seen % 2 == 1) p = p.mirrored()
        if (seen >= 2) {
            val map = (0 until 8).shuffled(kotlin.random.Random(level * 131L + seen)).toIntArray()
            p = p.recolored(map)
        }
        return p
    }
